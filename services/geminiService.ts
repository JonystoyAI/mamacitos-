
import { GoogleGenAI } from "@google/genai";

// The API key is obtained from the environment variable `process.env.API_KEY`.
// It is assumed to be pre-configured and available in the execution context.
const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });

async function callGemini(prompt: string): Promise<string> {
  try {
    const response = await ai.models.generateContent({
      model: 'gemini-2.5-flash',
      contents: prompt,
    });
    
    // Using the recommended .text property to extract the response.
    const text = response.text;

    if (!text) {
      throw new Error("No text was generated by the API.");
    }

    return text.trim();
  } catch (error) {
    console.error("Error calling Gemini API:", error);
    throw new Error("Failed to generate content from Gemini API.");
  }
}


export async function generateProfileBio(keywords: string): Promise<string> {
  const prompt = `
    You are a witty and charming assistant for a dating app called "Mamacitos". 
    Your goal is to write an engaging, sensual, yet respectful profile bio in Spanish for a user. The platform is for the transgender community and those who admire them.
    Based on these keywords provided by the user: "${keywords}", write a short, captivating bio (2-3 sentences).
    Keep it classy, alluring, and positive. Do not include hashtags.
  `;
  return callGemini(prompt);
}

export async function generatePortfolioDescription(keywords: string): Promise<string> {
    const prompt = `
    You are a professional and creative assistant for service providers on a platform called "Mamacitos".
    Your task is to write a compelling "About Me" description for a provider's public portfolio based on their keywords. The tone should be elegant, professional, and inviting.
    The audience might not be registered on the app, so the text should serve as a standalone professional introduction.
    Keywords provided by the user: "${keywords}".
    Write a captivating description of about 3-4 sentences in Spanish. Focus on highlighting their unique qualities and the experience they offer.
  `;
  return callGemini(prompt);
}
